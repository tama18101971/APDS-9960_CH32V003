#ifndef APDS9960_H
#define APDS9960_H

/*
 * apds9960.h — Драйвер распознавания жестов для APDS9960 (CH32V003)
 *
 * Поддерживает: влево, вправо, вверх, вниз.
 * Интерфейс: I2C (адрес 0x39).
 * Потребление RAM: ~20 байт статика + ~8 байт стек.
 */

#include <stdint.h>
#include <stdbool.h>

/* Перечисление типов жестов */
typedef enum {
    GESTURE_NONE = 0,   /* Жест не определен */
    GESTURE_LEFT,       /* Движение влево */
    GESTURE_RIGHT,      /* Движение вправо */
    GESTURE_UP,         /* Движение вверх */
    GESTURE_DOWN        /* Движение вниз */
} gesture_t;

/* ============================================================================
 * НАСТРАИВАЕМЫЕ ПАРАМЕТРЫ (можно переопределить через #define перед #include)
 * ============================================================================ */

/*
 * APDS_GAIN — Усиление приемника proximity-канала (регистр CONTROL, биты [3:2])
 *
 * Значения:
 *   0 = PGAIN_1X  — усиление 1x
 *   1 = PGAIN_2X  — усиление 2x
 *   2 = PGAIN_4X  — усиление 4x  (по умолчанию)
 *   3 = PGAIN_8X  — усиление 8x
 *
 * Больше усиление = больше чувствительность, но больше шум.
 * Рекомендуется 4x для расстояния 5-10 см.
 */
#ifndef APDS_GAIN
#define APDS_GAIN               3           /* PGAIN_8X = максимальное усиление */
#endif

/*
 * APDS_LED_CURRENT — Ток светодиода при proximity/ALS измерении
 * (регистр CONTROL, биты [7:6])
 *
 * Значения:
 *   0 = 100 mA  (по умолчанию)
 *   1 = 50 mA
 *   2 = 25 mA
 *   3 = 12.5 mA
 *
 * Больше ток = больше дальность, но больше энергопотребление.
 */
#ifndef APDS_LED_CURRENT
#define APDS_LED_CURRENT        0           /* 100 mA — максимум для дальности */
#endif

/*
 * APDS_FIFO_MIN_PACKETS — Минимальное количество пакетов FIFO
 * для принятия решения о жесте
 *
 * При значении 4 датчик должен накопить минимум 4 пакета (U/D/L/R)
 * перед определением направления. Больше = стабильнее, но медленнее.
 */
#ifndef APDS_FIFO_MIN_PACKETS
#define APDS_FIFO_MIN_PACKETS   4           /* Минимум 4 пакета FIFO */
#endif

/*
 * APDS_PROX_THRESHOLD — Порог входа в жестовый режим (регистр GPENTH)
 *
 * Когда proximity-значение превышает этот порог, датчик начинает
 * заполнять FIFO жестовыми данными.
 *
 * 0   = максимальная чувствительность (срабатывает отдалённо)
 * 50  = среднее расстояние ~5-10 см (по умолчанию)
 * 255 = минимальная чувствительность (нужно очень близко)
 */
#ifndef APDS_PROX_THRESHOLD
#define APDS_PROX_THRESHOLD     50          /* Порог входа: ~5-10 см */
#endif

/*
 * APDS_GESTURE_EXIT_TH — Порог выхода из жестового режима
 * (регистр GEXTH)
 *
 * Когда proximity-значение падает ниже этого порога, датчик прекращает
 * сбор жестовых данных. Должен быть меньше GPENTH.
 *
 * 30 = выход при удалении руки (по умолчанию)
 */
#ifndef APDS_GESTURE_EXIT_TH
#define APDS_GESTURE_EXIT_TH    30          /* Порог выхода: ниже порога входа */
#endif

/*
 * APDS_GESTURE_TIMEOUT_MS — Максимальное время ожидания жеста (мс)
 *
 * Если за это время не получен ни один жест, функция readGesture()
 * вернет GESTURE_NONE.
 *
 * 300 мс = достаточно для быстрого взмаха руки (по умолчанию)
 * 1000 мс = для медленных жестов
 */
#ifndef APDS_GESTURE_TIMEOUT_MS
#define APDS_GESTURE_TIMEOUT_MS 300         /* 300 мс — таймаут жеста */
#endif

/*
 * APDS_GGAIN — Усиление жестового канала (регистр GCONF2, биты [4:3])
 *
 * Значения:
 *   0 = GGAIN_1X  — усиление 1x
 *   1 = GGAIN_2X  — усиление 2x
 *   2 = GGAIN_4X  — усиление 4x  (по умолчанию)
 *   3 = GGAIN_8X  — усиление 8x
 *
 * Управляет чувствительностью 4-х фотодиодов жестового канала.
 */
#ifndef APDS_GGAIN
#define APDS_GGAIN              3           /* GGAIN_8X = максимальное усиление */
#endif

/*
 * APDS_GLDRIVE — Ток жестового светодиода (регистр GCONF2, биты [6:5])
 *
 * Значения:
 *   0 = 100 mA  (по умолчанию)
 *   1 = 50 mA
 *   2 = 25 mA
 *   3 = 12.5 mA
 *
 * Этот светодиод используется только в режиме жестов.
 */
#ifndef APDS_GLDRIVE
#define APDS_GLDRIVE            0           /* 100 mA — максимум */
#endif

/* Отладочный вывод: раскомментируйте следующую строку или определите
 * APDS9960_DEBUG при сборке (-DAPDS9960_DEBUG) для включения printf */
/* #define APDS9960_DEBUG */

/*
 * APDS_GWTIME — Время ожидания между жестовыми измерениями
 * (регистр GCONF2, биты [2:0])
 *
 * Значения:
 *   0 = 0 мс
 *   1 = 2.8 мс  (по умолчанию)
 *   2 = 5.6 мс
 *   3 = 8.4 мс
 *   4 = 14.0 мс
 *   5 = 22.4 мс
 *   6 = 30.8 мс
 *   7 = 39.2 мс
 *
 * Время в режиме пониженного питания между опросами FIFO.
 * Короче = быстрее отклик, но больше энергопотребление.
 */
#ifndef APDS_GWTIME
#define APDS_GWTIME             1           /* 2.8 мс — компромисс скорость/энергия */
#endif

/* ============================================================================
 * ПАРАМЕТРЫ АВТОМАТИЧЕСКОЙ КАЛИБРОВКИ
 * ============================================================================ */

/* Включение автокалибровки порогов proximity при apds_init().
 * 1 = включена (по умолчанию), 0 = отключена (используются APDS_PROX_THRESHOLD/GEXTH). */
#ifndef APDS_ENABLE_CALIBRATION
#define APDS_ENABLE_CALIBRATION     1
#endif

/* Количество замеров PDATA для калибровки (на стеке, ~32 байт). */
#ifndef APDS_CAL_SAMPLES
#define APDS_CAL_SAMPLES            32
#endif

/* Коэффициент σ для порога: порог = mean + N * σ.
 * 3 = промышленный стандарт, 2 = более чувствительно, 5 = жёстче. */
#ifndef APDS_CAL_SIGMA_COEFF
#define APDS_CAL_SIGMA_COEFF        3
#endif

/* Минимальный порог proximity (защита от шума при нулевом фоне). */
#ifndef APDS_CAL_PROX_MIN
#define APDS_CAL_PROX_MIN           10
#endif

/* Максимальный порог proximity (насыщение). */
#ifndef APDS_CAL_PROX_MAX
#define APDS_CAL_PROX_MAX           200
#endif

/* Порог отсева выбросов калибровки: PDATA > FILTER_MAX считаются насыщением и отбрасываются.
 * Если >50% замеров отброшены — калибровка неуспешна, используются дефолты. */
#ifndef APDS_CAL_FILTER_MAX
#define APDS_CAL_FILTER_MAX         200
#endif

/* Коды ошибок драйвера */
#define APDS_ERR_NONE           0   /* Ошибок нет */
#define APDS_ERR_I2C            1   /* Ошибка I2C (NACK, таймаут) */
#define APDS_ERR_FIFO_OVERFLOW  2   /* Переполнение FIFO */
#define APDS_ERR_SENSOR_HANG    3   /* Датчик не отвечает */

/* ============================================================================
 * ПУБЛИЧНЫЙ API
 * ============================================================================ */

/* Инициализация датчика APDS9960 через I2C.
 * Проверяет ID (0xAB, 0xA8, 0x9C, 0x9E).
 * Настраивает все регистры для работы в жестовом режиме.
 * Включает proximity + gesture + wait.
 * Возвращает: true если датчик найден, false если не отвечает. */
bool apds_init(void);

/* Перевод датчика в режим сна.
 * Отключает proximity, gesture и wait, оставляя только PON.
 * Датчик потребляет минимальный ток (~1 мкА).
 * Возвращает: true всегда. */
bool apds_sleep(void);

/* Пробуждение датчика из режима сна.
 * Включает proximity + gesture + wait.
 * Возвращает: true если датчик отвечает. */
bool apds_wakeup(void);

/* Проверка наличия данных жеста.
 * Читает регистр GSTATUS и проверяет бит GVALID.
 * Если переполнение FIFO (GFOV) — выполняет переинициализацию.
 * Возвращает: true если данные готовы к чтению. */
bool apds_available(void);

/* Чтение распознанного жеста (блокирующая функция).
 * Читает пакеты из FIFO пока GVALID=1,
 * накапливает соотношения U/D и L/R, определяет направление.
 *
 * Алгоритм:
 *   1. Находит первый и последний действительный пакет в FIFO
 *   2. Вычисляет Ratio: (U-D)*100/(U+D) и (L-R)*100/(L+R)
 *   3. Считает дельту между первым и последним
 *   4. Накапливает дельту, пока GVALID=1
 *   5. Определяет направление по накопленной дельте
 *
 * Возвращает: gesture_t — тип жеста или GESTURE_NONE */
gesture_t apds_readGesture(void);

/* Чтение текущего значения proximity-канала (0-255).
 * Возвращает: true если чтение успешно. */
bool apds_readProximity(uint8_t *value);

/* Чтение регистра STATUS (0x93) для диагностики.
 * Возвращает: true если чтение успешно. */
bool apds_readStatus(uint8_t *value);

/* Получение кода последней ошибки драйвера.
 * Возвращает: APDS_ERR_* (0 = нет ошибок). */
uint8_t apds_getLastError(void);

/* Получение количества последовательных переинициализаций.
 * 0 = нормальная работа, >0 = возможны проблемы с датчиком. */
uint8_t apds_getReinitCount(void);

/* Переинициализация датчика с повторной калибровкой порогов proximity.
 * Полезно при изменении условий освещения или положения датчика.
 * Доступна только если APDS_ENABLE_CALIBRATION = 1.
 * Возвращает: true если калибровка успешна. */
bool apds_recalibrate(void);

#endif /* APDS9960_H */
